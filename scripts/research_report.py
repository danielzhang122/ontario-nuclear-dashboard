def run(con, name):
    """Every result of queries/<name>*.sql as a DataFrame. Files that also build a table (like 28) start with a
    CREATE statement; that one is skipped, because the table already exists and the database is opened read-only."""
    return [con.sql(s).df() for s in statements(name) if not s.upper().startswith("CREATE")]


def p_text(p):
    """A p-value in words a reader can use."""
    return "under 0.001" if p < 0.001 else f"{p:.3f}" if p < 0.01 else f"{p:.2f}"


